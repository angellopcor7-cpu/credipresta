// Service worker de CrediPresta — solo se encarga de recibir y mostrar
// notificaciones push (no cachea nada ni hace la app offline).

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

// Chrome exige que el service worker tenga un manejador de "fetch" para
// considerar la app instalable (aunque no cachee nada) — sin esto, Chrome
// puede negarse a instalarla con "esta app no se puede instalar". Solo deja
// pasar la petición tal cual, no cachea ni hace nada offline.
self.addEventListener("fetch", (event) => {
  event.respondWith(fetch(event.request));
});

self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { title: "CrediPresta", body: event.data ? event.data.text() : "" };
  }

  const title = data.title || "CrediPresta";
  const options = {
    body: data.body || "",
    icon: "/icon-192.png",
    badge: "/icon-192.png",
    data: { url: data.url || "/" },
  };

  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || "/";

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if ("focus" in client) {
          client.navigate(url);
          return client.focus();
        }
      }
      if (self.clients.openWindow) return self.clients.openWindow(url);
    })
  );
});
